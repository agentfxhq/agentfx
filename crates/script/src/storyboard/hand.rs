/// Advance of a space, units.
pub const SPACE: f64 = 3.6;
/// Gap between glyphs, units.
pub const GAP: f64 = 1.3;

/// A glyph as polylines (already smoothed), in units (cap height 6, baseline y = 6).
pub fn glyph(c: char) -> Option<(f64, Vec<Vec<(f64, f64)>>)> {
    let up: Vec<char> = c.to_uppercase().collect();
    let c = if up.len() == 1 { up[0] } else { c };
    // umlauts / accents: base letter + marks
    let (base, marks): (char, &str) = match c {
        'Ä' => ('A', "1.2,-1.3 1.25,-1.05|3.0,-1.3 3.05,-1.05"),
        'Ö' => ('O', "1.3,-1.3 1.35,-1.05|3.1,-1.3 3.15,-1.05"),
        'Ü' => ('U', "1.1,-1.3 1.15,-1.05|2.9,-1.3 2.95,-1.05"),
        'É' | 'È' | 'Ê' => ('E', "1.2,-1.6 2.4,-0.6"),
        'Á' | 'À' | 'Â' => ('A', "1.5,-1.6 2.7,-0.6"),
        'Ó' | 'Ò' | 'Ô' => ('O', "1.6,-1.6 2.8,-0.6"),
        'Ñ' => ('N', "~0.6,-1.0 1.3,-1.5 2.1,-1.1 2.9,-0.8 3.5,-1.3"),
        'Ç' => ('C', "2.0,6 2.3,6.8 1.6,7.2"),
        '\u{2026}' => ('.', ""),
        _ => (c, ""),
    };
    let (_, adv, s) = GLYPHS.iter().find(|g| g.0 == base)?;
    let mut strokes = parse(s);
    if !marks.is_empty() {
        strokes.extend(parse(marks));
    }
    Some((*adv, strokes))
}

fn parse(s: &str) -> Vec<Vec<(f64, f64)>> {
    s.split('|')
        .map(|st| {
            let (smooth, body) = match st.strip_prefix('~') {
                Some(b) => (true, b),
                None => (false, st),
            };
            let pts: Vec<(f64, f64)> = body
                .split_whitespace()
                .filter_map(|p| {
                    let (x, y) = p.split_once(',')?;
                    Some((x.parse().ok()?, y.parse().ok()?))
                })
                .collect();
            if smooth { catmull_rom(&pts, 6) } else { pts }
        })
        .filter(|p| !p.is_empty())
        .collect()
}

/// Smooth polyline through the points (uniform Catmull-Rom, `n` samples per segment).
pub fn catmull_rom(p: &[(f64, f64)], n: usize) -> Vec<(f64, f64)> {
    if p.len() < 3 {
        return p.to_vec();
    }
    let mut out = vec![p[0]];
    for i in 0..p.len() - 1 {
        let p0 = if i == 0 { p[0] } else { p[i - 1] };
        let (p1, p2) = (p[i], p[i + 1]);
        let p3 = if i + 2 < p.len() { p[i + 2] } else { p[i + 1] };
        for k in 1..=n {
            let t = k as f64 / n as f64;
            let (t2, t3) = (t * t, t * t * t);
            let f = |a: f64, b: f64, c: f64, d: f64| 0.5 * (2.0 * b + (-a + c) * t + (2.0 * a - 5.0 * b + 4.0 * c - d) * t2 + (-a + 3.0 * b - 3.0 * c + d) * t3);
            out.push((f(p0.0, p1.0, p2.0, p3.0), f(p0.1, p1.1, p2.1, p3.1)));
        }
    }
    out
}

/// Width of a string in units (cap height 6).
pub fn width_units(s: &str) -> f64 {
    let mut w = 0.0;
    let mut first = true;
    for c in s.chars() {
        if c == ' ' {
            w += SPACE;
            first = true;
            continue;
        }
        let adv = glyph(c).or_else(|| glyph('?')).map(|g| g.0).unwrap_or(3.0);
        if !first {
            w += GAP;
        }
        w += adv;
        first = false;
    }
    w
}

/// Greedy word wrap for a cap height `cap` px within `max_w` px; at most `max_lines` lines
/// (the last one ends with "..." when the text does not fit).
pub fn wrap(s: &str, cap: f64, max_w: f64, max_lines: usize) -> Vec<String> {
    let u = cap / 6.0;
    let mut lines: Vec<String> = vec![];
    let mut cur = String::new();
    for word in s.split_whitespace() {
        let cand = if cur.is_empty() { word.to_string() } else { format!("{cur} {word}") };
        if width_units(&cand) * u <= max_w || cur.is_empty() {
            cur = cand;
        } else {
            lines.push(std::mem::take(&mut cur));
            cur = word.to_string();
        }
    }
    if !cur.is_empty() {
        lines.push(cur);
    }
    if lines.len() > max_lines {
        lines.truncate(max_lines);
        let last = lines.last_mut().unwrap();
        while !last.is_empty() && width_units(&format!("{last}...")) * u > max_w {
            match last.rfind(' ') {
                Some(i) => last.truncate(i),
                None => {
                    last.pop();
                }
            }
        }
        last.push_str("...");
    }
    lines
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn every_printable_ascii_has_a_glyph() {
        for c in (0x21u8..0x7f).map(|b| b as char) {
            assert!(glyph(c).is_some(), "no glyph for {c:?}");
        }
        assert!(glyph('ä').is_some() && glyph('\u{2013}').is_some());
    }
    #[test]
    fn wrap_respects_width() {
        let l = wrap("title scales in, grid scrolls, cut to tunnel", 12.0, 160.0, 3);
        assert!(l.len() >= 2);
        for x in &l {
            assert!(width_units(x) * 2.0 <= 160.0 + 1e-6 || !x.contains(' '), "{x}");
        }
    }
}
